#!/bin/sh
# Install windowping for the current user: a launcher in ~/.local/bin and an
# optional systemd user unit.  Re-running is safe.
#
#   ./install.sh              # launcher + systemd unit (enabled)
#   ./install.sh --no-systemd # launcher only
#   PREFIX=/usr/local ./install.sh
set -eu

REPO=$(cd "$(dirname "$0")" && pwd)
PREFIX=${PREFIX:-$HOME/.local}
BIN_DIR="$PREFIX/bin"
UNIT_DIR="${XDG_CONFIG_HOME:-$HOME/.config}/systemd/user"
PYTHON=${PYTHON:-/usr/bin/python3}

if [ ! -x "$PYTHON" ]; then
  echo "windowping: $PYTHON not found; set PYTHON=/path/to/python3" >&2
  exit 1
fi

"$PYTHON" - <<'PY' || { echo "windowping: python 3.11+ required" >&2; exit 1; }
import sys
raise SystemExit(0 if sys.version_info >= (3, 11) else 1)
PY

mkdir -p "$BIN_DIR"
cat > "$BIN_DIR/windowping" <<EOF
#!/bin/sh
# Generated by windowping install.sh — edits will be overwritten.
PYTHONPATH="$REPO\${PYTHONPATH:+:\$PYTHONPATH}"
export PYTHONPATH
exec "$PYTHON" -m windowping "\$@"
EOF
chmod 0755 "$BIN_DIR/windowping"
echo "installed launcher: $BIN_DIR/windowping"

if [ "${1:-}" = "--no-systemd" ]; then
  echo "skipping systemd unit"
  exit 0
fi

mkdir -p "$UNIT_DIR"
sed "s|@REPO@|$REPO|g" "$REPO/systemd/windowping.service" > "$UNIT_DIR/windowping.service"
systemctl --user daemon-reload
systemctl --user enable --now windowping.service
echo "systemd unit installed and started: windowping.service"
echo "  journalctl --user -u windowping.service -f"
