#!/bin/sh
# Install windowping for the current user: a launcher in ~/.local/bin, the live
# config, and (unless --no-systemd) a systemd user unit.  Re-running is safe.
#
#   ./install.sh              # launcher + config + systemd unit
#   ./install.sh --no-systemd # launcher + config only
#   PREFIX=/usr/local ./install.sh
set -eu

REPO=$(cd "$(dirname "$0")" && pwd)
PREFIX=${PREFIX:-$HOME/.local}
BIN_DIR="$PREFIX/bin"
PYTHON=${PYTHON:-/usr/bin/python3}

if [ ! -x "$PYTHON" ]; then
  echo "windowping: $PYTHON not found; set PYTHON=/path/to/python3" >&2
  exit 1
fi

"$PYTHON" - <<'PY' || { echo "windowping: python 3.11+ required" >&2; exit 1; }
import sys
raise SystemExit(0 if sys.version_info >= (3, 11) else 1)
PY

mkdir -p "$BIN_DIR"
cat > "$BIN_DIR/windowping" <<EOF
#!/bin/sh
# Generated by windowping install.sh — edits will be overwritten.
PYTHONPATH="$REPO\${PYTHONPATH:+:\$PYTHONPATH}"
export PYTHONPATH
exec "$PYTHON" -m windowping "\$@"
EOF
chmod 0755 "$BIN_DIR/windowping"
echo "installed launcher: $BIN_DIR/windowping"

# Seed the live config from a local ./config.toml (git-ignored working copy) the
# first time only — never overwrite an existing live config.
CONFIG_DIR="${XDG_CONFIG_HOME:-$HOME/.config}/windowping"
CONFIG_FILE="$CONFIG_DIR/config.toml"
mkdir -p "$CONFIG_DIR"
if [ -f "$REPO/config.toml" ] && [ ! -f "$CONFIG_FILE" ]; then
  install -m 0600 "$REPO/config.toml" "$CONFIG_FILE"
  echo "config seeded: $CONFIG_FILE (from $REPO/config.toml)"
elif [ -f "$CONFIG_FILE" ]; then
  chmod 0600 "$CONFIG_FILE" 2>/dev/null || true
  echo "config kept: $CONFIG_FILE"
else
  echo "no config yet:"
  echo "  windowping config init    # writes $CONFIG_FILE"
fi

if [ "${1:-}" = "--no-systemd" ]; then
  echo "skipping systemd unit"
  exit 0
fi

# The unit is generated by the CLI itself (windowping/service.py) so that the
# repo and an installed package produce an identical file.
"$BIN_DIR/windowping" service install --force
